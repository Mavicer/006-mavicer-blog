import test from 'node:test';
import assert from 'node:assert/strict';
import { fixture } from './helpers/api.mjs';
import { staticPostSql } from '../scripts/static-post-sql.mjs';
import { publishedPosts } from '../scripts/generate-static-posts.mjs';
const post = publishedPosts(new URL('../src/data/posts/', import.meta.url)).find((p) => p.slug === 'vpn-guide');
test('static API overrides stale D1 and preserves online-only articles', async () => {
  const f = fixture();
  f.sqlite.exec(`INSERT INTO post(slug,title,body) VALUES ('vpn-guide','old','obsolete'),('other','Other','untouched')`);
  const result = await f.request('/posts/vpn-guide');
  assert.equal(result.status,200);
  assert.equal(result.data.body,post.body);
  assert.equal(result.data.date,'2026-07-26');
  assert.equal(result.data.updated_at,'2026-11-03');
  assert.equal((await f.request('/posts/other')).data.body,'untouched');
  const list = (await f.request('/posts')).data;
  assert.equal(list.filter((p) => p.slug === 'vpn-guide').length,1);
  assert.equal(list.find((p) => p.slug === 'vpn-guide').title,post.title);
});
test('D1 upsert is idempotent and preserves interactions and unrelated articles', async () => {
  const f = fixture({legacy:true});
  f.sqlite.exec(`INSERT INTO post(slug,title,body,created_at) VALUES ('vpn-guide','old','obsolete','original'),('other','Other','untouched','original');
    INSERT INTO comment(post_slug,body) VALUES ('vpn-guide','keep');
    INSERT INTO "like"(post_slug,client_id) VALUES ('vpn-guide','keep');
    INSERT INTO favorite(post_slug,client_id) VALUES ('vpn-guide','keep');`);
  await f.request('/health');
  const user = await f.register('legacy');
  f.sqlite.prepare('INSERT INTO account_favorite(user_id,post_slug,created_at) VALUES (?,?,?)').run(user.data.user.id,'vpn-guide','original');
  const snapshot = () => ['comment','like','favorite','account_favorite'].map((t) => f.sqlite.prepare(`SELECT * FROM "${t}"`).all());
  const before = snapshot();
  f.sqlite.exec(staticPostSql('vpn-guide'));
  f.sqlite.exec(staticPostSql('vpn-guide'));
  const row = f.sqlite.prepare("SELECT * FROM post WHERE slug='vpn-guide'").get();
  assert.equal(row.body,post.body);
  assert.equal(row.created_at,'original');
  assert.equal(row.date,'2026-07-26');
  assert.equal(row.updated_at,'2026-11-03');
  assert.equal(f.sqlite.prepare("SELECT body FROM post WHERE slug='other'").get().body,'untouched');
  assert.deepEqual(snapshot(),before);
});
